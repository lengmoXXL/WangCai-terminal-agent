const { test } = require('node:test');
const assert = require('node:assert/strict');
const { mkdirSync } = require('node:fs');
const { join } = require('node:path');
const { createWorkspace, run, until, withHome } = require('@lengmoxxl/wangcai-testkit');
const { lists, names, settled, storedWorkspace, tabs } = require('./terminal-agent-ui.cjs');

test('a workspace named by hand keeps that name, and an empty one follows the directory again', { timeout: 180000 }, () => withHome('wangcai-rename', lists, async ({ home, open }) => {
  const beta = join(home, 'beta');
  let { page, close } = await open();
  const rename = async (name) => {
    await tabs(page).first().click({ button: 'right' });
    await page.getByRole('menuitem', { name: '重命名', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: '重命名工作区' });
    const input = dialog.getByRole('textbox');
    await dialog.waitFor();
    assert.equal(await input.inputValue(), await names(page).first().textContent(), 'the dialog opens on the name the row shows');
    await input.fill(name);
    await input.press('Enter');
    await dialog.waitFor({ state: 'hidden' });
  };
  for (const name of ['alpha', 'beta']) mkdirSync(join(home, name));
  await createWorkspace(page);
  await settled(page, ['~']);
  await run(page, 'cd alpha');
  await settled(page, ['alpha']);
  await rename('手写的名字');
  await settled(page, ['手写的名字']);
  assert.equal(storedWorkspace(home).name, '手写的名字');
  await run(page, 'cd ../beta');
  await until(() => storedWorkspace(home).cwd === beta);
  assert.equal(storedWorkspace(home).name, '手写的名字', 'a name written by hand stays');
  await settled(page, ['手写的名字']);
  await close();
  ({ page, close } = await open());
  await settled(page, ['手写的名字']);
  await rename('');
  await settled(page, ['beta']);
  assert.equal(storedWorkspace(home).name, 'beta', 'an empty name follows the directory again');
}));
